def category_sort_key(category: str) -> tuple[int, str]:
    """一覧の並び順。正規の分野は CANONICAL_CATEGORIES の順、それ以外
    （移行前のデータが残っている場合）は後ろにまとめて五十音順。"""
    if category in CATEGORY_ORDER:
        return (CATEGORY_ORDER[category], "")
    return (len(CANONICAL_CATEGORIES), category or "")


def classify(text: str, allowed: tuple[str, ...] | None = None) -> str | None:
    """本文から分野を推定する。決められなければ None。

    `allowed` を渡すとその分野だけを候補にする（産婦人科系→産科/婦人科の
    ような分割用）。判定は一致したキーワードの種類数が最多の分野を採り、
    同数なら RULES に先に書いた分野を優先する。
    """
    best: str | None = None
    best_hits = 0
    for category, keywords in RULES:
        if allowed is not None and category not in allowed:
            continue
        hits = sum(1 for k in keywords if k in text)
        if hits > best_hits:
            best, best_hits = category, hits
    return best


def normalize(category: str | None, text: str = "") -> str:
    """旧分野名を正規の分野名に直す。

    既に正規名ならそのまま返す。1対1で移せる旧名は読み替える。産婦人科系の
    ように分割が必要なものと分類未確定のものだけ、本文から推定し直す。
    """
    if category in CATEGORY_ORDER:
        return category
    if category in SPLIT_SOURCES:
        allowed, fallback = SPLIT_SOURCES[category]
        return classify(text, allowed) or fallback
    if category in OPEN_RECLASSIFY:
        return classify(text) or DEFAULT_CATEGORY
    mapped = LEGACY_EXACT.get(category or "")
    if mapped:
        return mapped
    return classify(text) or DEFAULT_CATEGORY
