# 上の語が出ても、主題が別にある設問。制度を問うものが多い。
DISCIPLINE_EXCEPT = ("母子健康手帳", "母子保健法", "検疫法", "社会保障", "医療費")


def _asked_sentence(text: str) -> str:
    """設問が何を問うているかの一文を取り出す。

    「〜はどれか。」で終わる文のうち最後のものを採る。選択肢はこの後ろに
    連結されているが、選択肢が「か。」で終わることはまず無いので当たらない。
    """
    found = re.findall(r"[^。\n]*か。", text)
    return found[-1] if found else ""


def discipline(text: str) -> str | None:
    """主題が学問領域そのものなら、その汎用名を返す。

    強い語が1つ出るか、弱い語が2つ以上そろったときだけ採る。臓器別の
    臨床問題を巻き込まないための線引きで、たとえば「胸部エックス線写真を
    示す」肺炎の設問は呼吸器のまま動かない。
    """
    if any(w in text for w in DISCIPLINE_EXCEPT):
        return None
    for generic, keywords in DISCIPLINE_STRONG:
        if any(k in text for k in keywords):
            return generic

    asked = _asked_sentence(text)
    for generic, keywords in DISCIPLINE_ASKED:
        if any(k in asked for k in keywords):
            return generic
    best: str | None = None
    best_hits = 1
    for generic, keywords in DISCIPLINE_WEAK:
        hits = sum(1 for k in keywords if k in text)
        if hits > best_hits:
            best, best_hits = generic, hits
    return best


