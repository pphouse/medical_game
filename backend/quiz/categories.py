def _exam(exam_type):
    return KOKUSHI if exam_type == KOKUSHI else CBT


def categories_for(exam_type):
    """その試験種別の科目一覧（表示順）。"""
    return CATEGORIES_BY_EXAM[_exam(exam_type)]


def default_category(exam_type):
    return DEFAULT_CATEGORY_BY_EXAM[_exam(exam_type)]


def category_sort_key(category: str, exam_type: str = CBT) -> tuple[int, str]:
    """一覧の並び順。正規の科目はその試験の並び、それ以外（移行前のデータが
    残っている場合）は後ろにまとめて五十音順。"""
    order = CATEGORY_ORDER_BY_EXAM[_exam(exam_type)]
    if category in order:
        return (order[category], "")
    return (len(order), category or "")


def category_for_blueprint_code(blueprint_code: str | None, exam_type: str = CBT) -> str | None:
    """出題基準コードから科目を決める。"D-5-4)-(2)-③" -> CBTなら "循環器"。

    まず "D-5" のような区分単位で引き、無ければ "D" のような大区分で引く
    （A/B/C/F/G は大区分ごとに1科目へまとめている）。
    """
    if not blueprint_code:
        return None
    table = BLUEPRINT_AREA_BY_EXAM[_exam(exam_type)]
    parts = blueprint_code.split("-")
    if len(parts) >= 2:
        found = table.get(f"{parts[0]}-{parts[1]}")
        if found:
            return found
    return table.get(parts[0])


def _to_category(generic: str | None, exam_type: str) -> str | None:
    """汎用の臓器名を、その試験の科目名に読み替える。"""
    if not generic:
        return None
    return GENERIC_BY_EXAM[_exam(exam_type)].get(generic)


def classify(text: str, allowed: tuple[str, ...] | None = None) -> str | None:
    """本文から汎用の臓器名を推定する。決められなければ None。

    `allowed` を渡すとその候補だけに絞る（産婦人科系→産科/婦人科のような
    分割用）。判定は一致したキーワードの種類数が最多の分野を採り、同数なら
    RULES に先に書いた分野を優先する。
    """
    best: str | None = None
    best_hits = 0
    for category, keywords in RULES:
        if allowed is not None and category not in allowed:
            continue
        hits = sum(1 for k in keywords if k in text)
        if hits > best_hits:
            best, best_hits = category, hits
    return best


# 国試だけ「消化管」と「肝・胆・膵」を分ける（CBTは「消化器」でひとまとめ）。
# 出題基準の D-7 は消化器系ひとまとめなので、本文の語で肝胆膵を切り出す。
# ここに書くのは肝胆膵にしか出てこない語だけ。「腹痛」「黄疸」のような
# 消化管側にも出る語を入れると、消化管の設問まで吸い寄せられる。
HEPATOBILIARY_KEYWORDS = (
    "肝硬変", "肝炎", "肝細胞癌", "肝不全", "肝性脳症", "脂肪肝", "肝生検",
    "門脈", "食道静脈瘤", "胆石", "胆囊炎", "胆嚢炎", "胆管炎", "胆管癌",
    "胆囊癌", "胆嚢癌", "総胆管", "膵炎", "膵癌", "膵頭", "膵管",
    "原発性胆汁性", "自己免疫性肝炎", "Wilson病", "ヘモクロマトーシス",
)


def _split_digestive(text: str) -> str:
    """国試の消化器の設問を「肝・胆・膵」と「消化管」に振り分ける。"""
    if any(k in text for k in HEPATOBILIARY_KEYWORDS):
        return "肝・胆・膵"
    return "消化管"


def normalize(
    category: str | None,
    text: str = "",
    blueprint_code: str | None = None,
    exam_type: str = CBT,
) -> str:
    """分野名をその試験種別の科目名に揃える。

    出題基準コードがあればそれを最優先する（本文からの推測より確実）。
    無い場合だけ、旧分野名の読み替えと本文からの推定にフォールバックする。
    """
    exam = _exam(exam_type)

    # 主題が学問領域そのものの設問は、臓器のコードより先に拾う。
    # ただし既定の受け皿へ動かすだけなら何もしない。CBT には放射線科が
    # 無く、放射線治療の設問を医学総論へ移すと腫瘍にあった方がましになる。
    from_discipline = _to_category(discipline(text), exam)
    if from_discipline and from_discipline != default_category(exam):
        return from_discipline

    result = _normalize_raw(category, text, blueprint_code, exam)
    # 国試の「消化管」は出題基準では肝胆膵と同じ区分なので、ここで分ける。
    if exam == KOKUSHI and result == "消化管":
        return _split_digestive(f"{category or ''}\n{text}")
    return result


def _normalize_raw(
    category: str | None, text: str, blueprint_code: str | None, exam: str
) -> str:
    from_code = category_for_blueprint_code(blueprint_code, exam)
    if from_code:
        return from_code

    order = CATEGORY_ORDER_BY_EXAM[exam]
    if category in order:
        return category

    if category in SPLIT_SOURCES:
        allowed, fallback = SPLIT_SOURCES[category]
        generic = classify(text, allowed) or fallback
        return _to_category(generic, exam) or default_category(exam)

    if category in OPEN_RECLASSIFY:
        return _to_category(classify(text), exam) or default_category(exam)

    generic = LEGACY_TO_GENERIC.get(category or "", category)
    mapped = _to_category(generic, exam)
    if mapped:
        return mapped

    return _to_category(classify(text), exam) or default_category(exam)
